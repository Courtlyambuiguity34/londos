import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import { format, resolveConfig } from "prettier";
export async function generateThemeRegistry(
  root = fileURLToPath(new URL("../", import.meta.url)),
  check = false,
) {
  const folder = join(root, "src/modules/shop-themes");
  const files = (await readdir(join(folder, "presets")))
    .filter((name) => name.endsWith(".json"))
    .sort();
  if (!files.length || files.length > 24)
    throw Error("Theme library supports 1–24 reviewed definitions.");
  const ids = [];
  for (const file of files) {
    const value = JSON.parse(await readFile(join(folder, "presets", file), "utf8"));
    if (
      !/^[a-z][a-z0-9-]{1,31}$/.test(value.id) ||
      file !== `${value.id}.json` ||
      ids.includes(value.id)
    )
      throw Error(`Invalid or duplicate theme identity in ${file}`);
    ids.push(value.id);
  }
  const output = await format(
    `// Generated by scripts/generate-shop-themes.mjs. Add reviewed preset JSON files; do not hand-edit.\n${ids.map((id, i) => `import theme${i} from "./presets/${id}.json" with { type: "json" };`).join("\n")}\nexport const themeIds = ${JSON.stringify(ids)} as const;\nexport const themeDefinitions = [${ids.map((_, i) => `theme${i}`).join(",")}] as const;\n`,
    {
      ...(await resolveConfig(join(root, "src/modules/shop-themes/registry.generated.ts"))),
      parser: "typescript",
    },
  );
  const path = join(folder, "registry.generated.ts");
  if (check) {
    if ((await readFile(path, "utf8")) !== output)
      throw Error("Theme registry is stale. Run npm run themes:generate.");
  } else await writeFile(path, output);
  return ids.length;
}
if (process.argv[1] === fileURLToPath(import.meta.url))
  console.log(
    `Shop theme registry: ${await generateThemeRegistry(undefined, process.argv.includes("--check"))} definitions.`,
  );
